def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def read_text(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except OSError:
        return ""


def missing_markers(text: str, markers: tuple[str, ...]) -> list[str]:
    return [marker for marker in markers if marker not in text]


class Report:
    def __init__(self) -> None:
        self.checks: dict[str, dict[str, object]] = {}

    def add(self, name: str, passed: bool, evidence: str, required: bool = True) -> None:
        self.checks[name] = {
            "passed": passed,
            "required": required,
            "evidence": evidence,
        }

    def to_dict(self, started_at: str, completed_at: str) -> dict[str, object]:
        failed_required = [
            name
            for name, check in self.checks.items()
            if check["required"] and check["passed"] is not True
        ]
        return {
            "startedAt": started_at,
            "completedAt": completed_at,
            "passed": not failed_required,
            "failedRequiredChecks": failed_required,
            "checks": self.checks,
        }


def add_marker_check(report: Report, name: str, text: str, markers: tuple[str, ...], pass_evidence: str) -> None:
    missing = missing_markers(text, markers)
    report.add(name, not missing, pass_evidence if not missing else "missing: " + ", ".join(missing))


def add_text_file_marker_checks(
    report: Report,
    present_name: str,
    structured_name: str,
    root: Path,
    relative_path: Path,
    markers: tuple[str, ...],
    pass_evidence: str,
) -> None:
    path = root / relative_path
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as error:
        report.add(present_name, False, f"missing text: {relative_path}: {error}")
        report.add(structured_name, False, f"missing text: {relative_path}: {error}")
        return

    report.add(present_name, True, str(relative_path))
    missing = missing_markers(text, markers)
    report.add(structured_name, not missing, pass_evidence if not missing else "missing: " + ", ".join(missing))


def read_json_text(path: Path) -> tuple[str, str | None]:
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError as error:
        return "", f"missing json: {path}: {error}"

    try:
        payload = json.loads(raw)
    except json.JSONDecodeError as error:
        return "", f"invalid json: {path}: {error}"

    return json.dumps(payload, ensure_ascii=False, sort_keys=True), None


def add_json_marker_checks(
    report: Report,
    present_name: str,
    structured_name: str,
    root: Path,
    relative_path: Path,
    markers: tuple[str, ...],
    pass_evidence: str,
) -> None:
    path = root / relative_path
    present = path.is_file()
    report.add(present_name, present, str(relative_path) if present else f"missing json: {relative_path}")
    json_text, error = read_json_text(path)
    if error:
        report.add(structured_name, False, error)
        return

    missing = missing_markers(json_text, markers)
    report.add(structured_name, not missing, pass_evidence if not missing else "missing: " + ", ".join(missing))


