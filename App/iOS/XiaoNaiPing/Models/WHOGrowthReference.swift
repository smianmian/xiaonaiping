/// WHO 儿童生长标准（0–24 月龄）P3 / P50 / P97 参考值。
/// 数值取自 WHO Child Growth Standards 公开百分位表（保留一位小数）。
/// 仅作图表参考带展示，不构成医疗建议；生长评估请以儿保医生为准。
enum WHOGrowthReference {
    struct Point {
        let month: Int
        let p3: Double
        let p50: Double
        let p97: Double
    }

    enum Metric {
        case weight
        case height
        case head
    }

    enum Sex {
        case boy
        case girl

        init(babySex: String) {
            self = babySex.contains("女") ? .girl : .boy
        }
    }

    static func points(metric: Metric, sex: Sex) -> [Point] {
        let table: [[Double]]
        switch (metric, sex) {
        case (.weight, .boy): table = weightBoys
        case (.weight, .girl): table = weightGirls
        case (.height, .boy): table = heightBoys
        case (.height, .girl): table = heightGirls
        case (.head, .boy): table = headBoys
        case (.head, .girl): table = headGirls
        }
        return table.enumerated().map { month, values in
            Point(month: month, p3: values[0], p50: values[1], p97: values[2])
        }
    }

